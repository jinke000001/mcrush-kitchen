import {test,expect} from '@playwright/test';
import {interactKitchen,prepareCola,startKitchen,waitKitchen,walkKitchen,workKitchen} from './kitchen-helpers';
test.use({viewport:{width:1600,height:900},video:{mode:'on',size:{width:1600,height:900}},trace:'off'});
test('演示录像：真实操作三关教学与伙伴接力',async({page})=>{
  test.setTimeout(360000);
  await startKitchen(page,'',true);
  await interactKitchen(page,'meat');await interactKitchen(page,'grill-a');
  await waitKitchen(page,w=>w.stations.find(s=>s.id==='grill-a')?.state==='ready');
  await interactKitchen(page,'grill-a');await interactKitchen(page,'pass-s0');
  await interactKitchen(page,'bun');await interactKitchen(page,'pass-s0');await interactKitchen(page);
  await interactKitchen(page,'serve-a');
  await waitKitchen(page,w=>w.tutorial?.stage==='handoff');
  await interactKitchen(page,'potato');await interactKitchen(page,'chop-a');await workKitchen(page,'chop-a','cutPotato');
  await interactKitchen(page);await interactKitchen(page,'pass-n0');
  await page.keyboard.press('q');await page.keyboard.press('1');await page.keyboard.press('e');
  await waitKitchen(page,w=>!!w.actors[1].assist);await page.waitForTimeout(1000);await page.keyboard.press('q');
  await walkKitchen(page,{x:4.5,y:7.5});await waitKitchen(page,w=>w.tutorial?.stage==='combo',60000);
  await page.keyboard.press('Escape');await page.getByRole('button',{name:'返回标题',exact:true}).click();
  await page.getByRole('button',{name:/选择关卡 2/}).click();
  await page.getByRole('button',{name:'实操教学',exact:true}).click();
  await prepareCola(page);await interactKitchen(page,'pass-n0');
  await waitKitchen(page,w=>!!w.stations.find(s=>s.id==='pass-n3')?.itemId,20000);
  await interactKitchen(page,'pass-n3');await interactKitchen(page,'serve-a');
  await waitKitchen(page,w=>w.phase==='prep');
  await page.keyboard.press('Escape');await page.getByRole('button',{name:'返回标题',exact:true}).click();
  await page.getByRole('button',{name:/选择关卡 3/}).click();
  await page.getByRole('button',{name:'实操教学',exact:true}).click();
  await prepareCola(page);await interactKitchen(page,'serve-b');
  await expect(page.getByTestId('guide')).toContainText('堂食');await page.waitForTimeout(1500);
  await interactKitchen(page,'serve-a');await prepareCola(page);await interactKitchen(page,'serve-b');
  await waitKitchen(page,w=>w.phase==='prep');await page.waitForTimeout(1500);
});
